import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(webRoot, "..", "..");
const assetRoot = path.join(
  repositoryRoot,
  "docs",
  "design-system",
  "assets",
  "space-ai-native",
  "attribution",
);
const outputPath = path.join(
  webRoot,
  "src",
  "components",
  "brand-attribution-masks.ts",
);
const documentationCssPath = path.join(assetRoot, "brand-attribution-masks.css");

const assets = [
  ["SPACE_WORDMARK_MASK", "space-mark-parametric-wordmark-mask.svg", "--brand-mask-space-wordmark"],
  ["SPACE_FOCUS_MASK", "space-mark-parametric-focus-mask.svg", "--brand-mask-space-focus"],
  ["SPACE_ORBIT_MASK", "space-mark-parametric-orbit-mask.svg", "--brand-mask-space-orbit"],
  ["SPACE_ORBIT_BACK_MASK", "space-mark-parametric-orbit-back-mask.svg", "--brand-mask-space-orbit-back"],
  ["SPACE_ORBIT_FRONT_MASK", "space-mark-parametric-orbit-front-mask.svg", "--brand-mask-space-orbit-front"],
  ["ATTRIBUTION_STANDARD_POWERED_BY_MASK", "formal-standard-powered-by-mask.svg", "--brand-mask-standard-powered-by"],
  ["ATTRIBUTION_STANDARD_AI_MASK", "formal-standard-ai-mask.svg", "--brand-mask-standard-ai"],
  ["ATTRIBUTION_STANDARD_NATIVE_MASK", "formal-standard-native-mask.svg", "--brand-mask-standard-native"],
  ["ATTRIBUTION_COMPACT_POWERED_BY_MASK", "formal-compact-powered-by-mask.svg", "--brand-mask-compact-powered-by"],
  ["ATTRIBUTION_COMPACT_AI_MASK", "formal-compact-ai-mask.svg", "--brand-mask-compact-ai"],
  ["ATTRIBUTION_COMPACT_NATIVE_MASK", "formal-compact-native-mask.svg", "--brand-mask-compact-native"],
];

const masks = await Promise.all(
  assets.map(async ([name, fileName, cssVariable]) => {
    const svg = await readFile(path.join(assetRoot, fileName));
    const dataUrl = `url(\"data:image/svg+xml;base64,${svg.toString("base64")}\")`;
    return { name, cssVariable, dataUrl };
  }),
);

const source = [
  "// Generated by scripts/build-brand-attribution-masks.mjs. Do not edit directly.",
  ...masks.map(({ name, dataUrl }) => `export const ${name} = ${JSON.stringify(dataUrl)};`),
  "",
].join("\n");
const documentationCss = [
  "/* Generated by apps/web/scripts/build-brand-attribution-masks.mjs. */",
  ":root {",
  ...masks.map(({ cssVariable, dataUrl }) => `  ${cssVariable}: ${dataUrl};`),
  "}",
  "",
].join("\n");

await writeFile(outputPath, source, "utf8");
await writeFile(documentationCssPath, documentationCss, "utf8");
console.log(
  `Generated ${path.relative(repositoryRoot, outputPath)} and ${path.relative(repositoryRoot, documentationCssPath)} from approved SVG masks.`,
);
